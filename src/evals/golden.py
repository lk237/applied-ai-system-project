"""
The golden set: human-authored expectations.

These 26 cases are the human checkpoint in the architecture diagram. Nothing
here is generated by a model - each case encodes a judgement about what a
correct answer looks like, written by a person who knows the catalog.

Each case carries a paraphrase, which is what makes the consistency metric
meaningful. Re-running an identical query against a greedy-decoded model
trivially returns the same answer, so measuring that would produce a flattering
1.0 that means nothing. Asking the same thing in different words is the property
a user actually cares about.

Assertion style: only the checks a case specifies are evaluated, and a case
passes relevance only if all of its specified checks hold. Checks are written
against catalog *properties* rather than exact song ids wherever possible, so
adding songs to the catalog does not invalidate the expectation.
"""

from __future__ import annotations

from dataclasses import dataclass, field
from typing import List, Optional, Sequence


@dataclass(frozen=True)
class GoldenCase:
    id: str
    query: str
    paraphrase: str
    rationale: str                                    # why a human expects this

    # --- property assertions (all optional) ---------------------------------
    genres_any: Sequence[str] = ()      # top pick's genre contains one of these
    moods_any: Sequence[str] = ()       # top pick's mood is one of these
    energy_at_least: Optional[float] = None   # applies to top pick
    energy_at_most: Optional[float] = None    # applies to top pick
    all_energy_at_least: Optional[float] = None   # applies to every pick
    all_energy_at_most: Optional[float] = None    # applies to every pick
    expect_refusal: bool = False        # catalog genuinely has nothing


