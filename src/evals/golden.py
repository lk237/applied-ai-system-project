def case_count() -> int:
    return len(GOLDEN_CASES)


def refusal_cases() -> List[GoldenCase]:
    return [case for case in GOLDEN_CASES if case.expect_refusal]


def recommendation_cases() -> List[GoldenCase]:
    return [case for case in GOLDEN_CASES if not case.expect_refusal]
